"""support_search.py -- which sub-multigraphs H of Gamma carry an element of order 16?

Gamma is K_4 with the edges 01, 02, 03, 12, 13 doubled and 23 single, in the edge order
    (0,1),(0,2),(0,3),(1,2),(1,3),(2,3),(0,1),(0,2),(0,3),(1,2),(1,3)
and n = 5.  Its torsion is T = (Z/2)^7 + (Z/8)^4 + Z/16, generated by the cycles in a generator file written
by "certificates/certq 2 2 4 -1".

A sub-multigraph H is given by its edge multiplicities m(ab) <= m_Gamma(ab).  For each H the program runs
certificates/orderq with the missing copies deleted (the primed copies, indices 6..10, are deleted first;
base half-edges are moved into H when needed), and kernel.py then gives T cap im(H_2(Conf_5 H)).

Search.  Start from Gamma and lower one multiplicity at a time.  The property "the image contains an element
of order 16" is monotone (a larger subgraph has a larger image), so only the children of subgraphs that have
the property need to be examined.  Subgraphs are identified up to the symmetries of Gamma, the group of order
4 generated by the vertex swaps (01) and (23) (both preserve the multiplicities).  Results already computed
are reused from the cache folder.

Usage:  python3 support_search.py generators_file graph_file cache_folder [max_level]
        graph_file: Gamma in the format "V E n" + edges.  One JSON line per subgraph is printed and appended to
        cache_folder/support_search.jsonl.  Each orderq run takes about 5 minutes and 3 GB.
"""
import json
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kernel import analyse, structure

HERE = os.path.dirname(os.path.abspath(__file__))
ORDERQ = os.path.join(HERE, "..", "..", "..", "..", "certificates", "orderq")
EDGES = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3), (0, 1), (0, 2), (0, 3), (1, 2), (1, 3)]
PAIRS = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]
FULL = {(0, 1): 2, (0, 2): 2, (0, 3): 2, (1, 2): 2, (1, 3): 2, (2, 3): 1}
# symmetries of Gamma, as vertex maps
G = [lambda v: v,
     lambda v: {0: 1, 1: 0}.get(v, v),
     lambda v: {2: 3, 3: 2}.get(v, v),
     lambda v: {0: 1, 1: 0, 2: 3, 3: 2}[v]]


def canon(m):
    """Canonical form of a multiplicity vector up to the symmetries of Gamma."""
    best = None
    for g in G:
        mm = tuple(sorted((tuple(sorted((g(a), g(b)))), c) for (a, b), c in m.items()))
        if best is None or mm < best:
            best = mm
    return best


def deletion(m):
    """Edge indices to delete (later copies first) and base overrides for orderq."""
    dl = []
    for (a, b) in PAIRS:
        have = [i for i, e in enumerate(EDGES) if e == (a, b)]
        dl += sorted(have, reverse=True)[:len(have) - m[(a, b)]]
    dl = sorted(dl)
    over = []
    for v in range(4):
        hs = [h for h in range(2 * len(EDGES)) if EDGES[h // 2][h % 2] == v]
        ok = [h for h in hs if h // 2 not in dl]
        if ok and hs[0] // 2 in dl:          # the lowest half-edge is gone: use the lowest remaining one
            over.append(f"{v}:{ok[0]}")
    return dl, over


def run(m, gens, graph, cache):
    """T cap image of H_2(Conf_5 H) for the sub-multigraph with multiplicities m (orderq, cached), as (structure, generator image orders)."""
    tag = "_".join(f"{a}{b}x{n}" for (a, b), n in sorted(m.items()))
    out = os.path.join(cache, f"ss_{tag}.json")
    if not os.path.exists(out) or os.path.getsize(out) == 0:
        dl, over = deletion(m)
        with open(graph) as g, open(out, "w") as o, open(out[:-5] + ".log", "w") as e:
            subprocess.run([ORDERQ, "2", "2", "6", gens, ",".join(map(str, dl)) or "-", ",".join(over) or "-"],
                           stdin=g, stdout=o, stderr=e, check=True)
    d, oc, ks, tot = analyse(out)
    return structure(oc), [c["order_in_M"] for c in d["cycles"]]


def main(gens, graph, cache, maxlevel=11):
    """The downward search; one JSON line per sub-multigraph examined."""
    os.makedirs(cache, exist_ok=True)
    level, seen = [dict(FULL)], {canon(FULL)}
    res = open(os.path.join(cache, "support_search.jsonl"), "a")
    for L in range(1, maxlevel + 1):
        nxt = []
        for m in level:
            for p in PAIRS:
                if m[p] == 0:
                    continue
                c = dict(m)
                c[p] -= 1
                k = canon(c)
                if k in seen:
                    continue
                seen.add(k)
                st, imgs = run(c, gens, graph, cache)
                rec = {"level": L, "mult": {f"{a}{b}": n for (a, b), n in sorted(c.items())},
                       "T_cap_image": st, "has_order16": 16 in st, "generator_image_orders": imgs}
                print(json.dumps(rec), flush=True)
                res.write(json.dumps(rec) + "\n")
                res.flush()
                if 16 in st:
                    nxt.append(c)
        level = nxt
        if not level:
            break


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 11)
