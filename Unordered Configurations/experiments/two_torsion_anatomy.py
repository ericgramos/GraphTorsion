#!/usr/bin/env python3
"""
What IS a 2-torsion class?  Ko--Park's class versus the planar class, cell by cell.

THE PICTURE BEING TESTED
------------------------
The basic 1-dimensional class in a graph braid group is the STAR CLASS (the "Y-exchange"):
two particles near a vertex of degree >= 3 trade places by using three of its edges.
UConf_2 of the tripod K_{1,3} is a circle, so H_1(B_2 K_{1,3}) = Z, generated by this loop.
Its orientation depends on a cyclic order of the three edges -- a chirality.

    H_1 torsion (Ko--Park).  Claim: the Z/2 in H_1(B_2 Gamma) for non-planar Gamma is a single
        star class S_v pushed in from a tripod at one vertex, and 2 S_v = 0.  The geometric
        reason is a loop in the configuration space that carries the exchange at v back to
        itself with its chirality REVERSED: the family of circles over that loop is a Klein
        bottle, and the fibre of a Klein bottle has order two in H_1.  Reversing a chirality
        needs the graph to be non-planar -- a planar embedding fixes a coherent cyclic order at
        every vertex -- which is Ko--Park's theorem seen from this side.

    H_2 torsion (planar).  Claim: the basic 2-dimensional class is a TORUS of two simultaneous
        exchanges, at two different vertices u and w, which needs 2 + 2 = 4 particles.  That is
        what the theta graph's H_2(B_4 Theta) = Z is, and it is why planar torsion starts at
        k = 4.  The torus has a second way to reverse orientation that a circle does not:
        INTERCHANGE ITS TWO FACTORS.  (a,b) |-> (b,a) has determinant -1 on H_2(T^2).  A loop
        in the configuration space that swaps the two exchange sites therefore makes the torus
        class equal to its own negative, and the Wang sequence of that family -- the mapping
        torus of the swap -- gives exactly coker(phi_* - 1) = coker(-2) = Z/2.  Swapping two
        sites needs no chirality reversal, so planarity does not obstruct it.

So both are the same phenomenon -- an orientation-reversing monodromy on a product of exchange
circles -- and they differ only in WHICH orientation-reversing symmetry is available: a
reflection of one factor (needs non-planarity) or a transposition of two factors (needs only
room for two exchanges and a way to move them past each other).

WHAT THIS SCRIPT CHECKS
-----------------------
    (A) star classes in degree one: push the generator of H_1(B_2 K_{1,3}) into a graph at k=2
        and compute its order.  Prediction: exactly 2 in K_{3,3} and K_5, infinite in a planar
        graph.
    (B) the theta class IS a torus of two exchanges: in a theta graph whose branches have
        length 3, the tripods at the two hubs are vertex-disjoint, so the product of their two
        star classes is a 2-cycle on 4 particles.  Prediction: it generates H_2(B_4 Theta) = Z.
    (C) theta classes in degree two: push the generator of H_2(B_4 Theta) into a graph and
        compute its order.  Prediction: exactly 2 in the octahedron, and not of order 2 in
        the triangular prism, which has no torsion.

HOW ORDERS ARE COMPUTED
-----------------------
Every complex here is the UNREDUCED Swiatkowski complex, which is functorial for inclusions of
subgraphs: a basis element of the subgraph's complex maps to the basis element of G with the
same states (renamed edges), and this is a chain map.  The generator of H_d of the small graph
(the tripod at k = 2, d = 1; the theta at k = 4, d = 2) is found as a kernel vector z of d_d
whose class is a generator: adjoining z to the columns of d_{d+1} raises the rank by one and
adds no torsion.  It is then pushed into G, giving a d-cycle s of G.

Orders are computed exactly: m.s lies in the image of d iff adjoining it as a column changes
neither the rank nor the invariant factors (a finitely generated abelian group is Hopfian, so
G / <g> = G forces g = 0), and s has infinite order iff adjoining it raises the rank.  Orders
m = 1..8 are tried; a larger finite order is reported as "finite > 8".

WHAT IS PRINTED
---------------
(A) one row per graph, columns  graph | planar | vertex ("v -> [three neighbours]", the
    tripod used) | order of the star class.
(B) the number of terms of the product of the two hub exchanges in theta(3,3), whether it is
    a 2-cycle, and whether it generates H_2(B_4 theta) = Z.
(C) one row per graph, columns  graph | planar | theta (hubs; branch lengths) | order, with
    the time taken.  (The planar column of (C) is not computed: both graphs are planar.)

Output of the full run (about 40 seconds):

    graph          planar   vertex     order of the star class
    K_{3,3}        False    0 -> [3, 4, 5] 2
    K_5            False    0 -> [1, 2, 3] 2
    K_4            True     0 -> [1, 2, 3] infinite
    prism          True     0 -> [1, 2, 3] infinite
    octahedron     True     0 -> [2, 3, 4] infinite
    ...
       it is a 2-cycle on 4 particles:          True
       it generates H_2(B_4 theta) = Z:         True
    ...
    graph        planar   theta (hubs; branches)         order
    octahedron   True     0,1; 2,2,2                     2   [20s]
    prism        True     0,3; 1,3,3                     infinite   [20s]

USAGE, DATA FILE AND EXIT CODE
------------------------------
    python3 experiments/two_torsion_anatomy.py          (no options; about 40 seconds)

Writes data/two_torsion_anatomy.json with keys "A|<graph>" and "C|<graph>", each
{"order": "2" | "infinite" | "0" | "finite > 8" ...}, and "B" = {"is_cycle": bool,
"generates": bool}.  Always exits 0 (the predictions are checked by eye from the table); a
RuntimeError is raised if no generator of H_d of the small graph can be found.
"""

import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from gbt import (Graph, complete, complete_bip, octahedron, paths,            # noqa: E402
                 prism, swiatkowski, tetrahedron, theta)
from gbt.linalg import indexed_columns, kernel_basis, sparse_smith           # noqa: E402

DATA_FILE = "two_torsion_anatomy.json"


# ---------------------------------------------------------------------------
# subgraph complexes and push-forward
# ---------------------------------------------------------------------------

def subgraph_complex(G, sub_edges, k):
    """The unreduced weight-k complex of a subgraph, and its push-forward into G.

    The subgraph is built on its own vertex set, so that it has no isolated vertices (which
    would add spurious components to its configuration space).  Vertices are relabelled in
    increasing order, so the order of moving slots -- and with it every Koszul sign -- is
    preserved by the push-forward.
    """
    verts = sorted({x for e in sub_edges for x in e})
    vi = {v: i for i, v in enumerate(verts)}
    H = Graph(len(verts), [(vi[a], vi[b]) for a, b in sub_edges])
    eG = {frozenset(e): i for i, e in enumerate(G.edges)}
    glob = {i: eG[frozenset((verts[a], verts[b]))] for i, (a, b) in enumerate(H.edges)}

    def push(gen):
        """Image in G of a basis element (mono, st) of the subgraph's complex."""
        mono, st = gen
        nst = [0] * G.N
        for lv, x in enumerate(st):
            if x == 0:
                continue
            nst[verts[lv]] = 1 if x == 1 else 2 + glob[x - 2]
        return (tuple(sorted(glob[e] for e in mono)), tuple(nst))

    return swiatkowski(H, k), push


def generator_of_Z(C, d):
    """A cycle generating H_d(C) when H_d(C) = Z, as {index into degree-d gens: coeff}.

    Searches the kernel basis of d_d, then sums of two basis vectors, for a cycle whose class
    is +-1: adjoining it to d_{d+1} must raise the rank by one and add no torsion.
    """
    up, _, _ = indexed_columns(C, d + 1)
    here, _, gens_d = indexed_columns(C, d)
    Z = kernel_basis(here, len(C.gens.get(d - 1, ())))
    r0, t0 = sparse_smith(up, verbose=False) if up else (0, [])

    def is_generator(z):
        """True if the cycle z spans H_d = Z: rank of [d_{d+1} | z] up by one, torsion
        unchanged.  (Rows of `up` and the indices of z both follow the repr order of the
        degree-d generators, as indexed_columns guarantees.)"""
        r, t = sparse_smith(up + [z], verbose=False)
        return r == r0 + 1 and t == t0

    for z in Z:
        if is_generator(z):
            return z, gens_d
    for i in range(len(Z)):
        for j in range(i + 1, min(len(Z), i + 40)):
            for s in (1, -1):
                z = dict(Z[i])
                for key, v in Z[j].items():
                    z[key] = z.get(key, 0) + s * v
                    if z[key] == 0:
                        del z[key]
                if z and is_generator(z):
                    return z, gens_d
    raise RuntimeError("no generator found among kernel vectors and pair sums")


def order_in(G, k, d, chain):
    """Order of the class of a d-cycle (given on G's degree-d gens) in H_d(B_k G).

    Returns ("infinite", None), ("zero", 1) or ("finite", m).
    """
    C = swiatkowski(G, k)
    up, index_d, _ = indexed_columns(C, d + 1)
    s = {}
    for gen, c in chain.items():
        r = index_d[gen]
        s[r] = s.get(r, 0) + c
        if s[r] == 0:
            del s[r]
    r0, t0 = sparse_smith(up, verbose=False)
    r1, _ = sparse_smith(up + [s], verbose=False)
    if r1 == r0 + 1:
        return "infinite", None
    for m in range(1, 9):
        ms = {r: m * v for r, v in s.items()}
        r, t = sparse_smith(up + [ms], verbose=False)
        if r == r0 and t == t0:
            return ("zero", 1) if m == 1 else ("finite", m)
    return "finite > 8", None


def pushed_chain(G, sub_edges, k, d):
    """A generator of H_d(B_k sub) = Z, pushed into G, as {G-generator: coefficient}.

    `sub_edges` are edges of G (in G's labels) spanning the subgraph; H_d of the subgraph
    must be infinite cyclic (generator_of_Z raises otherwise)."""
    C, push = subgraph_complex(G, sub_edges, k)
    z, gens_d = generator_of_Z(C, d)
    out = {}
    for j, c in z.items():
        g = push(gens_d[j])
        out[g] = out.get(g, 0) + c
        if out[g] == 0:
            del out[g]
    return out


def tripod(G, v, nbrs):
    """The edges of the star at v towards the vertices `nbrs` (in G's labels).

    With three neighbours this is the tripod K_{1,3}, whose H_1(B_2) = Z is the star class."""
    return [(v, w) for w in nbrs]


# ---------------------------------------------------------------------------
# (B) the theta class is a torus of two exchanges
# ---------------------------------------------------------------------------

def moving(st):
    """The vertices at which a particle is moving in the state vector `st` (st[v] >= 2)."""
    return [v for v, x in enumerate(st) if x >= 2]


def merge(b1, b2):
    """Tensor two basis elements with disjoint vertex supports, with the Koszul sign.

    The moving generators of a basis element are read in increasing vertex order, so
    writing b1 (x) b2 in that order costs (-1)^(number of pairs x in b1, y in b2 with
    x > y).  Returns (the merged basis element, the sign)."""
    m1, s1 = b1
    m2, s2 = b2
    st = tuple(a + b for a, b in zip(s1, s2))
    inv = sum(1 for x in moving(s1) for y in moving(s2) if x > y)
    return (tuple(sorted(m1 + m2)), st), (-1) ** inv


def theta_is_a_torus():
    """Test (B): in theta(3,3), is the product of the two hub exchanges a generator of
    H_2(B_4 theta) = Z?

    Returns (is_cycle, generates, number of terms of the product, cls), where cls describes
    the class when it is a nonzero multiple of a generator, and is None otherwise."""
    T = theta(3, 3)                   # hubs 0 and 1, three branches of length 3
    hub_u, hub_w = 0, 1
    nu = T.nbrs(hub_u)
    nw = T.nbrs(hub_w)
    assert not (set(nu) & set(nw)), "the two tripods must be vertex-disjoint"
    Su = pushed_chain(T, tripod(T, hub_u, nu), 2, 1)
    Sw = pushed_chain(T, tripod(T, hub_w, nw), 2, 1)
    prod = {}
    for g1, c1 in Su.items():
        for g2, c2 in Sw.items():
            g, sg = merge(g1, g2)
            prod[g] = prod.get(g, 0) + c1 * c2 * sg
            if prod[g] == 0:
                del prod[g]
    C = swiatkowski(T, 4)
    up, index2, _ = indexed_columns(C, 3)
    here, _, _ = indexed_columns(C, 2)
    col = {index2[g]: c for g, c in prod.items()}
    # it must be a cycle ...
    from collections import defaultdict
    acc = defaultdict(int)
    for r, c in col.items():
        for rr, cc in here[r].items():
            acc[rr] += c * cc
    is_cycle = not any(acc.values())
    # ... and generate H_2 = Z: rank up by one, no torsion introduced
    r0, t0 = sparse_smith(up, verbose=False)
    r1, t1 = sparse_smith(up + [col], verbose=False)
    generates = (r1 == r0 + 1 and t1 == t0)
    cls = None
    if not generates and r1 == r0 + 1:
        cls = "class of absolute value %s" % (t1,)
    return is_cycle, generates, len(prod), cls


# ---------------------------------------------------------------------------

def main():
    """Run (A), (B), (C), print the tables and save the orders.  Returns 0."""
    res = paths.load_json(DATA_FILE)
    t_start = time.time()

    print("== (A) star classes in H_1, k = 2: the Ko--Park class ==\n")
    print("   push the generator of H_1(B_2 K_{1,3}) = Z (one exchange at one vertex)")
    print("   into the graph and compute its order\n")
    print("%-14s %-8s %-10s %s" % ("graph", "planar", "vertex", "order of the star class"))
    casesA = [("K_{3,3}", complete_bip(3, 3), 0, False),
              ("K_5", complete(5), 0, False),
              ("K_4", tetrahedron(), 0, True),
              ("prism", prism(), 0, True),
              ("octahedron", octahedron(), 0, True)]
    for name, G, v, planar in casesA:
        nb = G.nbrs(v)[:3]
        ch = pushed_chain(G, tripod(G, v, nb), 2, 1)
        kind, m = order_in(G, 2, 1, ch)
        shown = "infinite" if kind == "infinite" else ("0" if kind == "zero" else str(m))
        res["A|%s" % name] = {"order": shown}
        print("%-14s %-8s %-10s %s" % (name, planar, "%d -> %s" % (v, nb), shown), flush=True)

    print("\n== (B) the theta class is a torus of two exchanges ==\n")
    is_cycle, generates, nterms, cls = theta_is_a_torus()
    res["B"] = {"is_cycle": is_cycle, "generates": generates}
    print("   theta(3,3): hubs 0 and 1, branches of length 3, so the tripods at the two")
    print("   hubs are disjoint.  Product of their star classes: %d terms." % nterms)
    print("   it is a 2-cycle on 4 particles:          %s" % is_cycle)
    print("   it generates H_2(B_4 theta) = Z:         %s%s"
          % (generates, "" if generates or not cls else "  (%s)" % cls))

    print("\n== (C) theta classes in H_2, k = 4: the planar class ==\n")
    print("   push the generator of H_2(B_4 theta) = Z into the graph and compute its order\n")
    print("%-12s %-8s %-30s %s" % ("graph", "planar", "theta (hubs; branches)", "order"))
    OCT_THETA = [(0, 2), (2, 1), (0, 3), (3, 1), (0, 4), (4, 1)]
    PRISM_THETA = [(0, 3), (0, 1), (1, 4), (4, 3), (0, 2), (2, 5), (5, 3)]
    casesC = [("octahedron", octahedron(), OCT_THETA, "0,1; 2,2,2"),
              ("prism", prism(), PRISM_THETA, "0,3; 1,3,3")]
    for name, G, sub, desc in casesC:
        t0 = time.time()
        ch = pushed_chain(G, sub, 4, 2)
        kind, m = order_in(G, 4, 2, ch)
        shown = "infinite" if kind == "infinite" else ("0" if kind == "zero" else str(m))
        res["C|%s" % name] = {"order": shown}
        print("%-12s %-8s %-30s %s   [%.0fs]"
              % (name, True, desc, shown, time.time() - t0), flush=True)

    paths.save_json(DATA_FILE, res)
    print("\n[%.0fs]  wrote data/%s" % (time.time() - t_start, DATA_FILE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
